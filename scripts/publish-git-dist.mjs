// Publishes the assembled browser distribution (`dist/`) as an installable Git
// distribution commit on the `browser-dist` branch.
//
// Package managers and CDNs install a Git dependency only from a repository root, so
// each distribution commit holds exactly the assembled package at its root, plus a
// `SOURCE_SHA` file naming the source commit whose build produced those contents.
//
// The branch only fast-forwards: every new commit has the previous tip as its parent,
// and it is never force-pushed. A new commit is made only when the distribution
// contents change; `SOURCE_SHA` alone never causes one. Commits a consumer has pinned
// therefore stay reachable.
//
// Usage: node scripts/publish-git-dist.mjs [--dist dist] [--source <sha>]
//          [--remote origin] [--branch browser-dist] [--push]
import { spawnSync } from "node:child_process";
import { existsSync, mkdtempSync, readFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

export const REPOSITORY = "moritzbrantner/settings";
export const BRANCH = "browser-dist";
export const SOURCE_FILE = "SOURCE_SHA";
const GENERATED_FILES = [SOURCE_FILE, ".nojekyll"];
const BOT = {
  GIT_AUTHOR_NAME: "github-actions[bot]",
  GIT_AUTHOR_EMAIL: "41898282+github-actions[bot]@users.noreply.github.com",
  GIT_COMMITTER_NAME: "github-actions[bot]",
  GIT_COMMITTER_EMAIL: "41898282+github-actions[bot]@users.noreply.github.com",
};

export function assertCommit(commit) {
  if (!/^[0-9a-f]{40}$/u.test(commit ?? "")) {
    throw new Error(`Expected an exact 40-character commit, got ${commit}`);
  }
  return commit;
}

export function gitDependencySpecifier(commit, repository = REPOSITORY) {
  return `github:${repository}#${assertCommit(commit)}`;
}

export function commitMessage({ name, version, sourceCommit, repository = REPOSITORY }) {
  assertCommit(sourceCommit);
  return [
    `Publish ${name} ${version} from ${sourceCommit}`,
    "",
    `Source: https://github.com/${repository}/commit/${sourceCommit}`,
  ].join("\n");
}

// Prepares (and with `push`, publishes) the next distribution commit. Returns a summary.
export function publishGitDist({
  root,
  distDir,
  sourceCommit,
  remote = "origin",
  branch = BRANCH,
  push = false,
  repository = REPOSITORY,
  env: extraEnv = {},
}) {
  assertCommit(sourceCommit);
  const manifest = JSON.parse(readFileSync(resolve(distDir, "package.json"), "utf8"));
  for (const generated of GENERATED_FILES) {
    if (existsSync(resolve(distDir, generated))) {
      throw new Error(`${generated} is generated by the publisher and must not be in ${distDir}`);
    }
  }

  const gitDir = gitDirOf(root);
  const parent = fetchBranchTip(root, remote, branch);
  const scratch = mkdtempSync(join(tmpdir(), "settings-git-dist-"));
  try {
    const env = { GIT_DIR: gitDir, GIT_INDEX_FILE: join(scratch, "index"), GIT_WORK_TREE: distDir };
    git(distDir, ["add", "--all", "--force", "."], env);
    addFile(distDir, env, ".nojekyll", "");

    // Unchanged contents keep the previous commit, even though the source moved on.
    let changed = true;
    if (parent) {
      const parentSource = showFile(root, parent, SOURCE_FILE);
      if (parentSource !== null) {
        addFile(distDir, env, SOURCE_FILE, parentSource);
        changed = git(distDir, ["write-tree"], env) !== git(root, ["rev-parse", `${parent}^{tree}`]);
      }
    }

    let commit = parent;
    if (changed) {
      addFile(distDir, env, SOURCE_FILE, `${sourceCommit}\n`);
      const tree = git(distDir, ["write-tree"], env);
      const message = commitMessage({ name: manifest.name, version: manifest.version, sourceCommit, repository });
      commit = git(root, ["commit-tree", tree, ...(parent ? ["-p", parent] : []), "-m", message], {
        ...BOT,
        ...extraEnv,
      });
      // Never forced: the push is rejected unless it fast-forwards the remote branch.
      if (push) git(root, ["push", "--quiet", remote, `${commit}:refs/heads/${branch}`]);
    }

    return {
      schemaVersion: 1,
      name: manifest.name,
      version: manifest.version,
      source: sourceCommit,
      branch,
      parent,
      commit,
      changed,
      pushed: changed && push,
      dependency: gitDependencySpecifier(commit, repository),
    };
  } finally {
    rmSync(scratch, { recursive: true, force: true });
  }
}

function addFile(cwd, env, path, contents) {
  const blob = run("git", ["hash-object", "-w", "--stdin"], cwd, env, contents).trim();
  git(cwd, ["update-index", "--add", "--cacheinfo", `100644,${blob},${path}`], env);
}

function showFile(root, commit, path) {
  const result = spawnSync("git", ["cat-file", "blob", `${commit}:${path}`], { cwd: root, encoding: "utf8" });
  return result.status === 0 ? result.stdout : null;
}

function fetchBranchTip(root, remote, branch) {
  const listing = git(root, ["ls-remote", "--heads", remote, `refs/heads/${branch}`]);
  if (!listing) return null;
  const [tip] = listing.split(/\s+/u);
  git(root, ["fetch", "--no-tags", "--quiet", remote, `refs/heads/${branch}`]);
  if (git(root, ["rev-parse", "FETCH_HEAD"]) !== tip) {
    throw new Error(`${branch} moved while it was being fetched`);
  }
  return tip;
}

function gitDirOf(root) {
  return git(root, ["rev-parse", "--absolute-git-dir"]);
}

function git(cwd, args, env = {}) {
  return run("git", args, cwd, env).trim();
}

function run(command, args, cwd, env = {}, input = undefined) {
  const result = spawnSync(command, args, {
    cwd,
    encoding: "utf8",
    env: { ...process.env, ...env },
    input,
  });
  if (result.error) throw result.error;
  if (result.status !== 0) {
    throw new Error(`${command} ${args.join(" ")} failed:\n${result.stderr}`);
  }
  return result.stdout;
}

function option(argv, name, fallback) {
  const index = argv.indexOf(name);
  return index === -1 ? fallback : argv[index + 1];
}

function main(argv) {
  const root = fileURLToPath(new URL("../", import.meta.url));
  const report = publishGitDist({
    root,
    distDir: resolve(root, option(argv, "--dist", "dist")),
    sourceCommit: option(argv, "--source", git(root, ["rev-parse", "HEAD"])),
    remote: option(argv, "--remote", "origin"),
    branch: option(argv, "--branch", BRANCH),
    push: argv.includes("--push"),
  });
  const state = report.changed ? (report.pushed ? "published" : "prepared") : "unchanged";
  console.error(`${state} ${report.name} ${report.version} -> ${report.dependency}`);
  console.log(JSON.stringify(report, null, 2));
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main(process.argv.slice(2));
}

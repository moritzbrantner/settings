// Keeps the browser adapter, its declarations and the WASM exports in step, so an API bump
// cannot ship a declared method without an implementation or a call into a missing export.
//
// Run: node --test web/settings-browser.test.mjs
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import test from 'node:test';

const read = (path) => readFile(new URL(path, import.meta.url), 'utf8');
const adapter = await read('./settings-browser.js');
const declarations = await read('./settings-browser.d.ts');
const wasm = await read('../crates/settings-wasm/src/lib.rs');

const sorted = (values) => [...new Set(values)].sort();

function block(source, start) {
  const from = source.indexOf(start);
  assert.notEqual(from, -1, `missing ${start}`);
  return source.slice(from, source.indexOf('\n}', from));
}

test('adapter and declarations share the API version', () => {
  const version = /SETTINGS_BROWSER_API_VERSION = (\d+);/.exec(adapter)?.[1];
  const declared = /SETTINGS_BROWSER_API_VERSION: (\d+);/.exec(declarations)?.[1];
  assert.ok(version);
  assert.equal(declared, version);
});

test('every declared session method is implemented and nothing else is', () => {
  const declared = [
    ...block(declarations, 'export interface BrowserSettingsSession').matchAll(/^  (\w+)\(/gm),
  ].map((match) => match[1]);
  const implemented = [...block(adapter, 'class BrowserSettingsSession').matchAll(/^  (\w+)\(/gm)]
    .map((match) => match[1])
    .filter((name) => name !== 'constructor');
  assert.ok(declared.includes('applyStagedWithConfirmation'), 'declarations were not parsed');
  assert.deepEqual(sorted(implemented), sorted(declared));
});

test('the adapter only calls exported WASM session methods', () => {
  const exported = new Set([...wasm.matchAll(/pub fn (\w+)\(/g)].map((match) => match[1]));
  exported.add('free'); // generated by wasm-bindgen
  for (const [, name] of adapter.matchAll(/this\.#inner\.(\w+)\(/g)) {
    assert.ok(exported.has(name), `settings-wasm does not export ${name}`);
  }
});

test('overlay layers match the declared type and the Rust parser', async () => {
  const session = await read('../crates/settings-wasm/src/session.rs');
  const names = (text, quote) =>
    sorted([...text.matchAll(new RegExp(`${quote}(\\w+)${quote}`, 'g'))].map((match) => match[1]));
  const declared = names(/export type OverlayLayer = ([^;]+);/.exec(declarations)[1], "'");
  const layers = names(/const OVERLAY_LAYERS = \[([^\]]+)\]/.exec(adapter)[1], "'");
  const parsed = names(/const OVERLAYS: [^=]+= \[([^;]+)\];/.exec(session)[1], '"');
  assert.deepEqual(layers, declared);
  assert.deepEqual(parsed, declared);
});
